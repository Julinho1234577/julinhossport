const contenedor = document.getElementById("productos");


// ======================================================
// CREAR MENSAJE DE WHATSAPP
// ======================================================

function crearMensajeWhatsApp(producto) {

    // URL pública de tu página
    const dominio = "https://julinhosports.netlify.app/";

    // Convertimos la ruta de la imagen
    // en una URL pública
    const imagenURL =
        dominio + producto.imagen
            .split("/")
            .map(parte => encodeURIComponent(parte))
            .join("/");


    const mensaje =

        `Hola, JULINHOS SPORT 👋\n\n` +

        `Estoy interesado en el siguiente producto:\n\n` +

        `🧵 Producto: ${producto.nombre}\n` +

        `💰 Precio: ${producto.precio}\n\n` +

        `📷 Imagen del producto:\n` +

        `${imagenURL}\n\n` +

        `¿Podrían brindarme información y cotización?`;


    return encodeURIComponent(mensaje);

}

// ======================================================
// MOSTRAR PRODUCTOS
// ======================================================

function mostrarProductos(lista) {

    contenedor.innerHTML = "";


    // ==================================================
    // SI NO HAY PRODUCTOS
    // ==================================================

    if (lista.length === 0) {

        contenedor.innerHTML = `

            <div class="sin-productos">

                <h3>
                    Próximamente
                </h3>

                <p>
                    Estamos preparando los productos
                    de esta categoría.
                </p>

            </div>

        `;

        return;
    }


    // ==================================================
    // CREAR TARJETAS
    // ==================================================

    lista.forEach(producto => {

        const tarjeta = document.createElement("div");

        tarjeta.className = "producto";


        const mensaje = crearMensajeWhatsApp(producto);


        tarjeta.innerHTML = `

            <img
                src="${producto.imagen}"
                alt="${producto.nombre}"
                onerror="this.src='https://placehold.co/600x600?text=JULINHOS+SPORT'"
            >

            <div class="producto-info">

                <h3>
                    ${producto.nombre}
                </h3>

                <p>
                    Precio: ${producto.precio}
                </p>

                <a
                    href="https://wa.me/${numeroWhatsApp}?text=${mensaje}"
                    target="_blank"
                    rel="noopener noreferrer"
                    class="btn-producto"
                >
                    💬 Consultar por WhatsApp
                </a>

            </div>

        `;


        contenedor.appendChild(tarjeta);

    });

}


// ======================================================
// FILTRAR PRODUCTOS
// ======================================================

function filtrarProductos(categoria) {

    let productosFiltrados;


    // ==================================================
    // TODOS
    // SOLO DEMOSTRATIVOS
    // ==================================================

    if (categoria === "todos") {

        productosFiltrados = productos.filter(

            producto =>
                producto.demostrativo === true

        );

    }


    // ==================================================
    // CATEGORÍA
    // TODOS LOS PRODUCTOS DE ESA CATEGORÍA
    // ==================================================

    else {

        productosFiltrados = productos.filter(

            producto =>
                producto.categoria === categoria

        );

    }


    mostrarProductos(productosFiltrados);

}


// ======================================================
// BOTONES DE FILTRO
// ======================================================

const botonesFiltro =
    document.querySelectorAll(".filtro");


botonesFiltro.forEach(boton => {

    boton.addEventListener("click", function () {

        botonesFiltro.forEach(btn => {

            btn.classList.remove("activo");

        });


        this.classList.add("activo");


        const categoria =
            this.dataset.categoria;


        filtrarProductos(categoria);


        const catalogo =
            document.getElementById("catalogo");


        if (catalogo) {

            catalogo.scrollIntoView({

                behavior: "smooth"

            });

        }

    });

});


// ======================================================
// MENÚ MÓVIL
// ======================================================

const btnMenu =
    document.getElementById("btnMenu");

const menu =
    document.querySelector(".menu");


if (btnMenu && menu) {

    btnMenu.addEventListener("click", () => {

        menu.classList.toggle("menu-abierto");

    });

}


// ======================================================
// WHATSAPP GENERAL
// ======================================================

function abrirWhatsApp() {

    const mensaje = encodeURIComponent(

        "Hola, JULINHOS SPORT 👋\n\n" +

        "Quisiera solicitar información " +

        "sobre sus productos y una cotización."

    );

    window.open(

        `https://wa.me/${numeroWhatsApp}?text=${mensaje}`,

        "_blank"

    );

}


